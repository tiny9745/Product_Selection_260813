-- =====================================================================
-- V5：單一登入 — session 版本比對機制
--
-- 【這支 migration 推翻了既有的架構決議，必須先說清楚】
-- 既有程式碼裡的「六-4決議」明確記載：JWT 採無狀態設計，不做黑名單機制，
-- 密碼變更後其他裝置上尚未過期的舊 token 仍可繼續使用到自然過期為止。
-- 這是當時基於「6 週雛型時程、YAGNI」考量做的刻意取捨，不是疏漏。
--
-- 單一登入這個需求本質上就是要求「新登入會讓舊 token 失效」，這正是
-- 六-4決議刻意省略的黑名單／狀態追蹤機制。這支 migration 與後續的程式碼
-- 改動，是在明確的需求下推翻這個舊決議，不是延續它。
--
-- 【為什麼不用 0/1 布林欄位，改用遞增版本號】
-- 布林「是否在線上」欄位有個實務會咬人的問題：使用者關閉瀏覽器分頁
-- （沒按登出）、電腦當機、網路斷線，欄位會卡在 1，導致這個人下次登入被
-- 誤判成「已經登入中」而拒絕，變成合法使用者被自己鎖住。
--
-- 遞增版本號完全不需要判斷「有沒有人在線上」這種模糊狀態，只需要判斷
-- 「這把鑰匙還是不是最新的那一把」：每次登入把版本號加一並寫進新發出的
-- JWT 裡，之後每個請求比對 JWT 裡的版本號與資料庫目前的版本號是否一致，
-- 不一致就判定這個 token 失效。新登入自動讓舊 token 失效，不會有「忘記
-- 登出導致自己被鎖住」的問題——因為新登入永遠可以用最新版本蓋掉舊的。
-- =====================================================================

ALTER TABLE `app_users`
  ADD COLUMN `active_session_version` INT NOT NULL DEFAULT 0
      COMMENT '目前有效的登入版本號。每次登入／密碼變更／明確登出都會遞增；JwtAuthenticationFilter 比對 JWT 裡的版本號與此欄位是否一致，不一致視為 token 已失效（即使 JWT 本身尚未過期）';

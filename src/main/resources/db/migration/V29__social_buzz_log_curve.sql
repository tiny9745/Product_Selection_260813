-- =====================================================================
-- V29：「社群聲量熱度」改用對數曲線正規化
--
-- 問題：SOCIAL_BUZZ 以「近30天社群提及次數」（操作人員手填）依目標區間 0~300
-- 線性換算。提及次數是長尾分布——多數商品個位數、少數爆紅商品上百——線性時
-- 提及 10 次只有 3.3 分，一般商品全擠在 0 分附近；把上界壓低到 100 雖然讓一般
-- 商品有分數，但 100 次以上全部滿分，中高熱度之間又拉不開，兩邊都失真。
--
-- 做法：沿用 TARGET_BAND_NORMALIZE 與既有目標區間，只在 strategy_params 加上
-- logCurve = 1，改用對數曲線（見 ScoringAlgorithms.normalizeByBandLog）：
--   下界 0 分、上界 100 分、高於上界一律 100 分（端點語意不變），
--   中間以對數壓縮長尾：上界 300 時，10 次≈42 分、30 次≈60 分、100 次≈81 分。
--
-- 只更新目前啟用中的版本、不另建新版本：這是修正換算曲線，不是管理層改了因子
-- 定義；已審核商品的分數在審核當下已凍結於 review_records，不受影響。
-- 未審核商品會在下次重算（每日 00:05 或評分設定變更）時套用新曲線。
-- 目標區間上下界不動，已自行調整過上界的環境維持原值。
-- =====================================================================

UPDATE `factor_definitions`
   SET `strategy_params` = JSON_SET(COALESCE(`strategy_params`, JSON_OBJECT()), '$.logCurve', 1)
 WHERE `factor_code` = 'SOCIAL_BUZZ'
   AND `is_active` = 1
   AND `strategy_code` = 'TARGET_BAND_NORMALIZE';

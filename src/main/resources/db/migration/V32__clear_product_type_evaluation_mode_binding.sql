-- V32：解除大類與評估模式的綁定（product_types.default_evaluation_mode_id → NULL）
--
-- 【問題】設定頁「評估模式」切換「目前生效」模式、或調整自訂模式權重，
-- 商品分數都不會跟著變。
--
-- 【原因】ScoringService.resolveEvaluationModeId() 的優先順序是：
--   1. 商品所屬大類的 default_evaluation_mode_id（有值就用它）
--   2. system_settings.current_evaluation_mode_id（設定頁的「目前生效」）
-- 設計前提是「所有品類的 default_evaluation_mode_id 預設為 null，剛上線時全部
-- 商品都走全域設定」（見該方法註解）。但 V16／V17 建立 9 個系統預設大類時，
-- 沿用舊種子資料把 9 個大類全部綁了模式：
--   生鮮食品、農產品、冷凍食品 → 2（衝量）
--   地方名產、常溫食品、生活休閒 → 1（均衡）
--   日用品、家庭用品、3C產品   → 3（高利潤）
-- 結果每一個商品都走第 1 條路徑，全域設定永遠讀不到；自訂模式（id=4）沒有
-- 任何大類綁定，所以調整它的權重對任何商品都沒有影響。
-- 這個綁定目前也沒有任何 API 或畫面可以查看、修改。
--
-- 【做法】清空綁定，回到「全部商品依設定頁的目前生效模式計分」。欄位與
-- ScoringService 的品類優先邏輯都保留，之後若要做「依品類指定模式」，
-- 補上設定畫面後再由管理者設定即可。
--
-- 【影響】
--   - 部署後第一次發生評分設定變更（切換模式、調整權重等）時，所有未核准商品
--     會改用目前生效模式（預設均衡）重算。原本綁衝量／高利潤的 6 個大類底下
--     的商品，分數與排名會變動。
--   - 已審核的商品有 review_records.weight_snapshot 保護，不受影響。
--   - 部署當下 product_evaluations 裡的分數不會自動重算（應用程式啟動時不重算
--     評分）。要立刻一致，部署後到設定頁重新選一次目前生效模式即可觸發全量重算。
--
-- 【順序】請在 V31__repair_other_risk_option.sql 之後套用。Flyway 預設不允許
-- 「版本號比已套用的還小」的 migration，若 V32 先上、V31 後上，啟動會驗證失敗。
--
-- 【冪等】可以重複執行。
-- =====================================================================

UPDATE `product_types`
SET `default_evaluation_mode_id` = NULL
WHERE `default_evaluation_mode_id` IS NOT NULL;
